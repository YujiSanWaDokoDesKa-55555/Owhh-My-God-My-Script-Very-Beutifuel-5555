def jumlah_pengguna():
    try:
        resp = requests.get(API_USER, timeout=5)
        if resp.status_code == 200:
            data = resp.json()
            if data.get("status"):
                return data.get("total_user", 0)
    except:
        pass
    return 0

def cek_versi():
    try:
        resp = requests.get(API_VERSI, timeout=5)
        if resp.status_code == 200:
            data = resp.json()
            if data.get("status"):
                return VERSI_TOOLS == data.get("versi", "")
    except:
        pass
    return True

